const DICTS: Record<Lang, Record<TKey, string>> = { ka, en, tr, ru }
const STORAGE_KEY = "site-lang"

function readLang(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === "ka" || v === "en" || v === "tr" || v === "ru") return v
  } catch { /* storage blocked: use the default */ }
  return "ka"
}

type I18n = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: TKey) => string
  /** translation for a key built from data (e.g. a tag id); falls back to `fallback` */
  tx: (key: string, fallback: string) => string
}

const I18nContext = createContext<I18n | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)

  const setLang = useCallback((next: Lang) => {
    setLangState(next)
    try { localStorage.setItem(STORAGE_KEY, next) } catch { /* not persisted */ }
  }, [])

  useEffect(() => { document.documentElement.lang = lang }, [lang])

  const value = useMemo<I18n>(() => {
    const dict = DICTS[lang]
    return {
      lang,
      setLang,
      t: (key) => dict[key],
      tx: (key, fallback) => (dict as Record<string, string>)[key] ?? fallback,
    }
  }, [lang, setLang])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error("useI18n must be used inside <LanguageProvider>")
  return ctx
}
